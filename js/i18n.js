/* ---- i18n engine ---- */
let currentLang = localStorage.getItem('lang') || 'en';

function t(key) {
  return (translations[currentLang] && translations[currentLang][key]) ||
         (translations.en[key]) || key;
}

function applyI18n(root = document) {
  // Replace innerHTML for elements with data-i18n
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val !== key) el.innerHTML = val;
  });
  // Replace attributes: data-i18n-attr="attr:key"
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    const spec = el.getAttribute('data-i18n-attr');
    const [attr, key] = spec.split(':');
    const val = t(key);
    if (val !== key) el.setAttribute(attr, val);
  });
  // Update <title> and meta if present
  const titleKey = document.documentElement.getAttribute('data-i18n-title');
  if (titleKey) document.title = t(titleKey);
}

function setLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('lang', lang);
  applyI18n();
  document.documentElement.lang = lang;
  // Notify pages (usage guide, dynamic text) that language changed
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
}

function getLang() {
  return currentLang;
}

// Init on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.lang = currentLang;
  applyI18n();
});

// Expose
window.i18n = { t, setLang, getLang, applyI18n };
